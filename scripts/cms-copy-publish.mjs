// Generates migrations/0014_copy_v3_publish.sql: the COPY V2 rewrite
// (2026-09-02, client instruction: "rewrite the entire copy", sharper and
// more energetic, in the voice of the client's own Gemini draft, kept
// inside the site's truth rules) written into the CMS as DRAFT ONLY.
//
// Published copy is deliberately left untouched: the client reviews every
// page under ?preview=1 in the admin and presses Publish per page, which is
// the human-approval gate this site is built around (R10, F-30, F-31).
// Nothing a visitor sees changes until that happens.
//
// Every value is read from src/lib/cms/content.ts (the *_DEFAULT
// constants, themselves taken from src/lib/site.ts), so code defaults and
// the CMS draft cannot drift.
//
// Usage:
//   node scripts/cms-copy-draft.mjs
//   npx wrangler d1 execute lahav-cms --local  --file=./migrations/0014_copy_v3_publish.sql
//   npx wrangler d1 execute lahav-cms --remote --file=./migrations/0014_copy_v3_publish.sql
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const now = new Date().toISOString();
const content = await import(pathToFileURL(path.join(ROOT, 'src/lib/cms/content.ts')).href);

const esc = (s) => s.replace(/'/g, "''");
const j = (v) => esc(JSON.stringify(v));

const lines = [
  '-- Generated by scripts/cms-copy-draft.mjs. Do not hand-edit.',
  '-- COPY V2 (2026-09-02) written as DRAFT only. Publish per page from /admin after review.',
  '',
];

const pages = {
  home: content.HOME_DEFAULT,
  about: content.ABOUT_DEFAULT,
  contact: content.CONTACT_DEFAULT,
  faq: content.FAQ_PAGE_DEFAULT,
  footer: content.FOOTER_DEFAULT,
};
for (const [id, value] of Object.entries(pages)) {
  lines.push(
    `UPDATE content_pages SET draft_json = '${j(value)}', published_json = '${j(value)}', draft_updated_at = '${now}', published_at = '${now}' WHERE id = '${id}';`,
    ''
  );
}
for (const slug of content.SERVICE_SLUGS) {
  lines.push(
    `UPDATE services_content SET draft_json = '${j(content.serviceDefault(slug))}', published_json = '${j(content.serviceDefault(slug))}', draft_updated_at = '${now}', published_at = '${now}' WHERE slug = '${slug}';`,
    ''
  );
}

const out = path.join(ROOT, 'migrations/0014_copy_v3_publish.sql');
fs.writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`wrote ${out}`);
