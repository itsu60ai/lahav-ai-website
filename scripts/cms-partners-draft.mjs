// Generates migrations/0016_partners_draft.sql: the partnership update
// (F-43, 2026-09-02) written into the CMS as DRAFT ONLY for the About
// page. Published content is untouched until the client reviews it under
// ?preview=1 and presses Publish -- same discipline as every earlier CMS
// content change on this project.
//
// Usage:
//   node scripts/cms-partners-draft.mjs
//   npx wrangler d1 execute lahav-cms --local  --file=./migrations/0016_partners_draft.sql
//   npx wrangler d1 execute lahav-cms --remote --file=./migrations/0016_partners_draft.sql
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const now = new Date().toISOString();
const content = await import(pathToFileURL(path.join(ROOT, 'src/lib/cms/content.ts')).href);

const esc = (s) => s.replace(/'/g, "''");
const j = (v) => esc(JSON.stringify(v));

const lines = [
  '-- Generated by scripts/cms-partners-draft.mjs. Do not hand-edit.',
  '-- Partnership update (F-43, 2026-09-02) written as DRAFT only for the',
  "-- 'about' row. Publish from /admin after the client reviews it.",
  '',
  `UPDATE content_pages SET draft_json = '${j(content.ABOUT_DEFAULT)}', draft_updated_at = '${now}' WHERE id = 'about';`,
  '',
];

const out = path.join(ROOT, 'migrations/0016_partners_draft.sql');
fs.writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`wrote ${out}`);
