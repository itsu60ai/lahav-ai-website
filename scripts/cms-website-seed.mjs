// Generates migrations/0008_website_seed.sql: the CURRENT approved
// website copy, written into the new content_pages / services_content /
// faq_items / site_settings tables as BOTH draft and published.
//
// This is a content-source migration, not a content change. Every value
// here is read from src/lib/cms/content.ts (the *_DEFAULT constants,
// themselves taken verbatim from src/lib/site.ts) -- nothing is
// rewritten, summarised, translated or improved. Draft and published are
// seeded to the SAME value on purpose: the CMS starts in exactly the
// state the live site is already in, so nothing changes for a visitor
// until someone actually edits and publishes something new.
//
// Usage:
//   node scripts/cms-website-seed.mjs
//   npx wrangler d1 execute lahav-cms --local  --file=./migrations/0008_website_seed.sql
//   npx wrangler d1 execute lahav-cms --remote --file=./migrations/0008_website_seed.sql
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const now = new Date().toISOString();

const content = await import(pathToFileURL(path.join(ROOT, 'src/lib/cms/content.ts')).href);
const site = await import(pathToFileURL(path.join(ROOT, 'src/lib/site.ts')).href);

const esc = (s) => s.replace(/'/g, "''");
const j = (v) => esc(JSON.stringify(v));

const lines = [
  '-- Generated by scripts/cms-website-seed.mjs. Do not hand-edit.',
  '-- Seeds the website CMS with the CURRENT approved copy, draft = published.',
  '',
];

// ── content_pages ──────────────────────────────────────────────────
const pages = {
  home: content.HOME_DEFAULT,
  about: content.ABOUT_DEFAULT,
  contact: content.CONTACT_DEFAULT,
  faq: content.FAQ_PAGE_DEFAULT,
  services: content.SERVICES_INDEX_DEFAULT,
  navigation: content.NAVIGATION_DEFAULT,
  footer: content.FOOTER_DEFAULT,
};
for (const [id, value] of Object.entries(pages)) {
  const json = j(value);
  lines.push(
    `INSERT INTO content_pages (id, draft_json, published_json, draft_updated_at, published_at)`,
    `VALUES ('${id}', '${json}', '${json}', '${now}', '${now}')`,
    `ON CONFLICT(id) DO NOTHING;`,
    ''
  );
}

// ── services_content ────────────────────────────────────────────────
for (const slug of content.SERVICE_SLUGS) {
  const json = j(content.serviceDefault(slug));
  lines.push(
    `INSERT INTO services_content (slug, draft_json, published_json, draft_updated_at, published_at)`,
    `VALUES ('${slug}', '${json}', '${json}', '${now}', '${now}')`,
    `ON CONFLICT(slug) DO NOTHING;`,
    ''
  );
}

// ── faq_items ────────────────────────────────────────────────────────
site.FAQ.forEach((f, i) => {
  const id = `seed-faq-${i + 1}`;
  lines.push(
    `INSERT INTO faq_items (id, question, answer, sort_order, enabled, created_at, updated_at)`,
    `VALUES ('${id}', '${esc(f.q)}', '${esc(f.a)}', ${i}, 1, '${now}', '${now}')`,
    `ON CONFLICT(id) DO NOTHING;`,
    ''
  );
});

// ── site_settings ────────────────────────────────────────────────────
for (const [key, value] of Object.entries(content.SETTINGS_DEFAULT)) {
  lines.push(
    `INSERT INTO site_settings (key, value, updated_at) VALUES ('${key}', '${esc(value)}', '${now}')`,
    `ON CONFLICT(key) DO NOTHING;`,
    ''
  );
}

const out = path.join(ROOT, 'migrations/0008_website_seed.sql');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote', out);
console.log('pages:', Object.keys(pages).length, '| services:', content.SERVICE_SLUGS.length, '| faq:', site.FAQ.length, '| settings:', Object.keys(content.SETTINGS_DEFAULT).length);
